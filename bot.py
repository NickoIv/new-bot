def news_hash(entry):
    return hashlib.md5((entry.get("link","") + entry.get("title","")).encode()).hexdigest()

def is_relevant(entry, country=None):
    text = (entry.get("title","") + " " + entry.get("summary","") + " " + entry.get("link","")).lower()
    if country:
        place_match = any(kw in text for kw in COUNTRY_KEYWORDS.get(country, []))
        if not place_match:
            return False
        # Упоминания топонима недостаточно — например, "China" встречается и в
        # новостях про политику/бизнес. Требуем ещё и туристическую тематику.
        return any(kw in text for kw in TOURISM_TOPIC_KEYWORDS)
    return any(kw in text for kw in ALL_KEYWORDS)

FEED_USER_AGENT = "sea-travel-bot/1.0 (+https://github.com/NickoIv/sea-travel-bot)"
RSS_FETCH_TIMEOUT_S = 12
TRANSLATE_WORKERS = 6

def _fetch_feed_entries(url: str) -> list:
    """feedparser.parse(url) сам ходит в сеть через urllib — и без таймаута.
    Один подвисший RSS-фид останавливал сбор новостей навсегда: пользователь
    так и видел «⏳ Собираю и перевожу новости...», а поток оставался занят.
    Качаем байты сами с жёстким таймаутом и отдаём парсеру готовое содержимое."""
    try:
        resp = requests.get(url, headers={"User-Agent": FEED_USER_AGENT}, timeout=RSS_FETCH_TIMEOUT_S)
        resp.raise_for_status()
        return feedparser.parse(resp.content).entries
    except Exception as e:
        log.warning(f"Feed fetch failed ({url}): {e}")
        return []

def _translate_many(texts: list[str]) -> list[str]:
    """Переводы идут параллельно. Последовательно это до 16 сетевых вызовов
    подряд (8 новостей × заголовок + анонс), каждый со своим таймаутом —
    дайджест собирался минутами, а внешний крон успевал отвалиться."""
    if not texts:
        return []
    out = list(texts)
    with ThreadPoolExecutor(max_workers=min(TRANSLATE_WORKERS, len(texts))) as pool:
        futures = {pool.submit(translate_to_russian, t): i for i, t in enumerate(texts)}
        for future in as_completed(futures):
            i = futures[future]
            try:
                result = future.result()
                if result:
                    out[i] = result
            except Exception as e:
                log.warning(f"Translate failed: {e}")
    return out

def fetch_news(limit=MAX_NEWS, country=None):
    # Раньше здесь на каждую новость (до ~180 за один сбор по всем фидам)
    # был отдельный синхронный запрос is_sent() -> load_data() к Upstash —
    # секунды блокировки event loop без всякой пользы. Грузим список уже
    # отправленных хэшей один раз и дальше проверяем в памяти.
    sent_hashes = set(load_data().get("sent_hashes", []))
    now = datetime.now(timezone.utc)
    seen, candidates = set(), []
    for feed_cfg in RSS_FEEDS:
        if country and feed_cfg["country"] not in (country, "all"):
            continue
        for entry in _fetch_feed_entries(feed_cfg["url"])[:20]:
            h = news_hash(entry)
            if h in seen or h in sent_hashes:
                continue
            if not is_relevant(entry, country):
                continue
            pub_dt, published = None, ""
            if getattr(entry, "published_parsed", None):
                pub_dt = datetime(*entry.published_parsed[:6], tzinfo=timezone.utc)
                if (now - pub_dt).days > 30:
                    continue
                published = _ru_short_date(pub_dt.astimezone(ALMATY_TZ))
            seen.add(h)
            candidates.append({
                "hash": h,
                "title": entry.get("title", ""),
                "link": entry.get("link", ""),
                "summary": re.sub(r'<[^>]+>', '', entry.get("summary", ""))[:400],
                "source": feed_cfg["name"],
                "flag": feed_cfg["flag"],
                "published": published,
                "pub_dt": pub_dt,
            })

    candidates.sort(key=lambda x: x["pub_dt"] or datetime.min.replace(tzinfo=timezone.utc),
                    reverse=True)
    # Переводим только то, что реально уйдёт в сообщение (после отсечки по limit).
    candidates = candidates[:limit]
    translations = _translate_many(
        [t for c in candidates for t in (c["title"], c["summary"])]
    )
    for i, c in enumerate(candidates):
        title_ru, summary_ru = translations[2 * i], translations[2 * i + 1]
        c["title"] = title_ru or c["title"] or "Без заголовка"
        c["summary"] = summary_ru or ""
        c.pop("pub_dt", None)
    return candidates

def fmt_item(item, i):
    summary = item.get("summary") or ""
    if summary:
        dot = summary.find(". ")
        if dot > 40:
            summary = summary[:dot+1]
        summary = f"\n<i>{esc(summary[:200])}</i>"
    date = f"  •  {esc(item['published'])}" if item.get("published") else ""
    link = safe_link(item.get("link", ""))
    link_line = f"\n<a href=\"{link}\">Читать →</a>" if link else ""
    return (
        f"{item.get('flag', '')} <b>{i}. {esc(item.get('title') or 'Без заголовка')}</b>\n"
        f"<code>{esc(item.get('source', ''))}{date}</code>"
        f"{summary}"
        f"{link_line}"
    )

