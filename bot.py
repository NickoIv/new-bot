def fmt_phrasebook(country_code: str) -> str:
    flag, name = COUNTRIES.get(country_code, ("", "?"))
    entries = PHRASEBOOK_DATA.get(country_code)
    if not entries:
        return "Информация недоступна"
    lines = "\n".join(
        f"{flag} <b>{ru}</b> — {local} <i>({translit})</i>"
        for ru, local, translit in entries
    )
    if country_code == "sg":
        return (
            f"🗣️ <b>Полезные словечки — {name}</b>\n\n"
            f"{lines}\n\n"
            f"<i>Английский в Сингапуре понимают везде — это официальный язык, полноценный разговорник не нужен, но эти словечки сделают тебя своим</i>"
        )
    return (
        f"🗣️ <b>Базовый разговорник — {name}</b>\n\n"
        f"{lines}\n\n"
        f"<i>Транскрипция приблизительная — просто читай как написано по-русски</i>"
    )

