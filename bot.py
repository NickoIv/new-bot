# ─── Безопасная вставка текста в HTML-сообщения ──────────────────────────────
# Всё, что приходит извне (заголовки и анонсы RSS, названия объектов из
# OpenStreetMap, поисковые запросы пользователя) попадает в сообщения с
# parse_mode="HTML". Telegram разбирает такой текст как настоящую разметку:
# один заголовок вида "Рейсы <дешевле> 100$" — и вся отправка падает с
# BadRequest "can't parse entities", пользователь не получает сообщение
# вообще, а в логе остаётся невнятная ошибка. Поэтому любой динамический
# текст обязан пройти через esc()/safe_link() — это не косметика, а защита
# от потери сообщений (и заодно от инъекции чужой разметки в наш текст).

def esc(value) -> str:
    """Экранирует динамический текст для текстового узла HTML-сообщения."""
    return html.escape(str(value if value is not None else ""), quote=False)

def safe_link(url) -> str:
    """Возвращает экранированный URL, пригодный для href="...", либо "".
    Пропускает только http/https — иначе javascript:/data: или кавычка в
    ссылке из RSS могли бы вырваться из атрибута и сломать разметку."""
    url = str(url or "").strip()
    if not url.lower().startswith(("http://", "https://")):
        return ""
    if any(ch in url for ch in ('"', "<", ">")):
        return ""
    return html.escape(url, quote=True)

