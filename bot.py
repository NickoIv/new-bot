# ─── Длинные сообщения ───────────────────────────────────────────────────────
# Telegram отклоняет текст длиннее 4096 символов («Message is too long»), а
# дайджест из 8 новостей с заголовком, источником, анонсом и ссылкой подходит
# к этому пределу вплотную. Без разбивки одна длинная новость ломала бы всю
# рассылку целиком — сообщение не получал никто.
TELEGRAM_MAX_MESSAGE_LEN = 4096

def split_message(text: str, limit: int = TELEGRAM_MAX_MESSAGE_LEN) -> list[str]:
    """Режет текст на части не длиннее limit, по возможности по границам
    блоков (пустая строка между новостями), чтобы не разорвать разметку."""
    if len(text) <= limit:
        return [text]
    chunks: list[str] = []
    current = ""
    for raw_block in text.split("\n\n"):
        block = raw_block
        candidate = f"{current}\n\n{block}" if current else block
        if len(candidate) <= limit:
            current = candidate
            continue
        if current:
            chunks.append(current)
        # Блок сам длиннее лимита — режем жёстко (на практике новость в разы
        # короче лимита, это только страховка от зависшего текста).
        while len(block) > limit:
            chunks.append(block[:limit])
            block = block[limit:]
        current = block
    if current:
        chunks.append(current)
    return chunks

async def send_long(bot, chat_id: int, text: str, **kwargs) -> None:
    """Отправляет текст, разбивая его на несколько сообщений при необходимости.
    Клавиатуру прикрепляем только к последней части, иначе она «прыгает»."""
    chunks = split_message(text)
    for i, chunk in enumerate(chunks):
        last = i == len(chunks) - 1
        await bot.send_message(chat_id, chunk, reply_markup=kwargs.get("reply_markup") if last else None,
                               parse_mode=kwargs.get("parse_mode"),
                               disable_web_page_preview=kwargs.get("disable_web_page_preview"))

async def edit_long(message, text: str, **kwargs) -> None:
    """Заменяет сообщение-заглушку («⏳ Собираю...») первой частью текста,
    остальные части отправляет следом отдельными сообщениями."""
    chunks = split_message(text)
    await message.edit_text(chunks[0], **kwargs)
    for chunk in chunks[1:]:
        await message.reply_text(chunk, **{k: v for k, v in kwargs.items() if k != "reply_markup"})

