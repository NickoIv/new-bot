async def _post_init(app: Application):
    """Регистрирует меню команд («/» в клиенте Telegram). Без этого в меню
    пусто, и про /subscribe и /status пользователь просто не узнаёт."""
    try:
        await app.bot.set_my_commands([BotCommand(c, d) for c, d in BOT_COMMANDS])
    except Exception as e:
        log.warning(f"set_my_commands failed: {e}")

def build_app() -> Application:
    app = Application.builder().token(BOT_TOKEN).post_init(_post_init).build()
    app.add_handler(CommandHandler("start", cmd_start))
    app.add_handler(CommandHandler("help", cmd_help))
    app.add_handler(CommandHandler("subscribe", cmd_subscribe))
    app.add_handler(CommandHandler("unsubscribe", cmd_unsubscribe))
    app.add_handler(CommandHandler("status", cmd_status))
    app.add_handler(InlineQueryHandler(inline_hotel_search))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_text))
    app.add_error_handler(on_error)
    return app

def run_polling_mode():
    app = build_app()
    # JobQueue управляется тем же event loop, что и run_polling — в отличие от
    # отдельного AsyncIOScheduler, запущенного до старта polling-цикла, задания
    # здесь гарантированно срабатывают по расписанию.
    app.job_queue.run_daily(
        send_daily_job,
        time=dtime(hour=5, minute=0, tzinfo=timezone.utc),  # 10:00 Алматы
    )
    log.info(f"🌴 {BOT_DISPLAY_NAME} запущен (polling)!")
    app.run_polling(drop_pending_updates=True)

# Защита от наложения рассылок: внешний крон может дёрнуть /cron/daily повторно,
# пока предыдущий сбор новостей ещё идёт, — тогда подписчики получили бы один и
# тот же дайджест дважды (второй раз «пустой», уже без новостей).
_digest_lock = asyncio.Lock()

async def _run_digest_once(bot):
    if _digest_lock.locked():
        log.info("Рассылка уже идёт — повторный запуск пропущен")
        return
    async with _digest_lock:
        await send_daily_digest(bot)

def run_webhook_mode():
    from aiohttp import web

    app = build_app()
    # Never place BOT_TOKEN in a public URL: reverse-proxy/request logs can be
    # retained outside our control. Telegram additionally signs every delivery
    # with the secret-token header configured through setWebhook.
    webhook_path = f"/webhook/{WEBHOOK_PATH_SECRET}"

    if not DAILY_CRON_SECRET:
        log.warning(
            "⚠️ DAILY_CRON_SECRET не задан — эндпоинт POST /cron/daily открыт кому угодно, "
            "кто знает адрес, и позволяет разослать дайджест подписчикам. "
            "Задай секрет и передавай его в заголовке X-Cron-Secret."
        )

    async def handle_webhook(request: web.Request):
        supplied = request.headers.get("X-Telegram-Bot-Api-Secret-Token", "")
        if not hmac.compare_digest(supplied, TELEGRAM_WEBHOOK_SECRET):
            return web.Response(status=403, text="forbidden")
        data = await request.json()
        update = Update.de_json(data, app.bot)
        await app.update_queue.put(update)
        return web.Response(status=200)

    async def handle_cron(request: web.Request):
        supplied = request.headers.get("X-Cron-Secret", "")
        if DAILY_CRON_SECRET and not hmac.compare_digest(supplied, DAILY_CRON_SECRET):
            return web.Response(status=403, text="forbidden")
        # Сборка новостей + перевод каждой через Google Translate может занять
        # больше 30 сек — это дольше таймаута большинства внешних крон-сервисов
        # (в т.ч. cron-job.org). Поэтому отвечаем сразу, а рассылку запускаем
        # фоновой задачей — cron просто "будит" эндпоинт, не дожидаясь результата.
        asyncio.create_task(_run_digest_once(app.bot))
        return web.Response(status=200, text="started")

    async def handle_health(request: web.Request):
        return web.Response(status=200, text="ok")

    async def run():
        await app.initialize()
        await app.start()
        web_app = web.Application()
        web_app.add_routes([
            web.post(webhook_path, handle_webhook),
            web.post("/cron/daily", handle_cron),
            web.get("/", handle_health),
            web.get("/health", handle_health),
        ])
        runner = web.AppRunner(web_app)
        await runner.setup()
        site = web.TCPSite(runner, "0.0.0.0", PORT)
        await site.start()
        log.info(f"🌴 {BOT_DISPLAY_NAME} запущен (webhook, порт {PORT})!")
        await asyncio.Event().wait()  # держим процесс живым

    asyncio.run(run())

def main():
    if not BOT_TOKEN:
        # Ненулевой код выхода: иначе хостинг считает запуск успешным и
        # бесконечно перезапускает контейнер, который заведомо не работает.
        log.error(
            "❌ BOT_TOKEN не задан. Возьми токен у @BotFather и передай его "
            "переменной окружения BOT_TOKEN (шаблон — в .env.example)."
        )
        raise SystemExit(1)
    if not re.fullmatch(r"\d{6,}:[A-Za-z0-9_-]{30,}", BOT_TOKEN):
        log.warning("BOT_TOKEN не похож на настоящий токен — возможно, скопирован не целиком.")
    if WEBHOOK_MODE and (not WEBHOOK_PATH_SECRET or not TELEGRAM_WEBHOOK_SECRET):
        log.error(
            "WEBHOOK_PATH_SECRET и TELEGRAM_WEBHOOK_SECRET обязательны в webhook-режиме. "
            "Не используй токен бота в URL webhook."
        )
        raise SystemExit(1)
    storage = "Upstash Redis" if (UPSTASH_URL and UPSTASH_TOKEN) else f"локальный файл {DATA_FILE.name}"
    log.info(f"Режим: {'webhook на порту ' + str(PORT) if WEBHOOK_MODE else 'polling'} · хранилище: {storage}")
    if WEBHOOK_MODE:
        run_webhook_mode()
    else:
        run_polling_mode()

if __name__ == "__main__":
    main()
